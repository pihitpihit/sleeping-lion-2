/**
 * 대문에 적는 모험 소식.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **여럿이면 세기만 한다.**                                                 │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * 하나면 어디서 도는지 적어 주는 것이 반갑지만, 둘만 되어도 이름이 늘어서 카드가
 * 무너진다 — 그때는 개수만 적고 자세한 것은 들어가서 본다(형님이 정했다).
 */
export function adventureNote(names: readonly string[]): string | null {
  if (names.length === 0) return null
  if (names.length === 1) return `${names[0]}에서 모험 중`
  return `${names.length}개의 모험`
}
