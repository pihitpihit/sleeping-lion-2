/**
 * 문 위에 걸린 간판 — 잠든 사자가 새겨진 놋쇠 원반.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **우리 그림이다.** Creator Pack이 아니므로 격리 규칙(1-1)에 걸리지 않는다. │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * 형님이 만들어 온 그림을 원 바깥(나무·돌 바탕)만 알파로 잘라 넣었다. 사각형
 * 채로 두면 그림 속 바탕색이 우리 배경과 어긋나 액자처럼 떠 보인다. 원으로
 * 자르면 어떤 배경 위에도 그냥 얹힌다.
 *
 * **빛무리는 그림에 있는 것만 쓰고 CSS로 더 얹는다.** 원본의 후광은 원 밖으로
 * 번지므로 자르는 순간 함께 잘린다. 잘린 자리를 `drop-shadow`로 메우면 어떤
 * 크기에서도 같은 두께로 번지고, 파일도 커지지 않는다.
 *
 * 앞의 `LionCrest`(도형으로 직접 그린 SVG)와 그것으로 만든 파비콘을 대신한다.
 * 둘 다 지웠다 — 쓰는 데가 없는 채로 두면 다음에 아이콘을 손볼 때 어느 쪽이
 * 진짜인지 헷갈린다. 되살릴 일이 생기면 이 커밋의 앞 판에 그대로 있다.
 *
 * 그림 속에 한글 간판이 새겨져 있지만 폰에서는 손톱만 해 읽히지 않는다. 그래서
 * 아래의 워드마크와 한글 이름줄은 그대로 둔다 — **새겨진 글자는 장식이고 읽는
 * 글자는 따로 있다.** 읽어주는 쪽에는 `alt`가 무엇이 그려져 있는지만 전한다.
 */

const BASE = `${import.meta.env.BASE_URL}assets/sign/`

export function SignMedallion({ className }: { className?: string }) {
  return (
    <img
      className={className}
      src={`${BASE}lion-medallion-640.webp`}
      /* 폰에서 640을 받을 이유가 없다. 실제로 그려지는 폭을 알려 주고 고르게 한다. */
      srcSet={`${BASE}lion-medallion-320.webp 320w, ${BASE}lion-medallion-640.webp 640w`}
      sizes="(max-width: 30rem) 30vw, 13rem"
      width={640}
      height={640}
      /* 첫 화면의 그림이라 미루지 않는다. 늦게 뜨면 간판이 한 번 껑충한다. */
      loading="eager"
      decoding="async"
      draggable={false}
      alt="금화와 보물 위에 잠든 사자가 새겨진 놋쇠 간판"
    />
  )
}
