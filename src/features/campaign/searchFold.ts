/**
 * 견주기 좋게 다듬은 글자.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **약간의 차이로 없다고 하면 같은 것이 두 벌 생긴다.**                     │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * 「가죽 장화」와 「가죽장화」는 같은 물건이다. 띄어쓰기 하나로 못 찾으면 **없는 줄
 * 알고 새로 적게 되고**, 그렇게 늘어난 목록은 다시 헷갈리게 한다(형님이 짚었다).
 * 그래서 찾을 때도 겹치는지 볼 때도 이 값으로 견준다.
 *
 * 하는 일은 셋이다:
 *   · **NFC로 모은다** — 맥에서 친 한글은 자모가 갈려 오는 일이 있어(NFD) 눈에는
 *     같아 보여도 글자로는 안 맞는다.
 *   · 대소문자를 지운다.
 *   · **공백을 통째로 뺀다** — 줄이는 것이 아니라 없앤다. 「가죽 장화」와
 *     「가죽장화」가 같아야 한다.
 *
 * **저장되는 이름은 사람이 친 그대로다.** 이 값은 견주는 데만 쓴다 — 다듬은 것을
 * 저장하면 화면에 「가죽장화」라고 뜬다.
 */
export function fold(text: string): string {
  return text.normalize('NFC').toLocaleLowerCase().replace(/\s+/g, '')
}
