import { describe, expect, it } from 'vitest'
import { splitPerkText } from './perkWords'

/**
 * 특혜 글은 관리자가 적어 넣은 우리말 문장이다(`0013`). 그 안에서 그림으로 바꿀
 * 낱말을 갈라내는 일은 **화면과 무관하게 정해진다** — 순수 함수로 떼어 덮는다.
 */

/** 읽기 쉽게 조각을 짧은 글로 편다. */
function shape(text: string): string[] {
  return splitPerkText(text).map((p) => {
    if (p.kind === 'text') return `"${p.text}"`
    if (p.kind === 'rolling') return '[굴림]'
    if (p.kind === 'value') return `[값:${p.valueId}]`
    return p.amount === null ? `[${p.def.id}]` : `[${p.def.id}:${p.amount}]`
  })
}

describe('낱말을 그림으로 가른다', () => {
  it('형님이 든 보기 그대로', () => {
    expect(shape('굴림 바람 카드 2장 추가')).toEqual(['[굴림]', '" "', '[air]', '" 카드 2장 추가"'])
  })

  it('그림으로 바꿀 것이 없으면 통째로 글이다', () => {
    expect(shape('카드 2장을 1장으로 교체')).toEqual(['"카드 2장을 1장으로 교체"'])
  })
})

/**
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **「이동불가」 안의 「불」을 잡으면 안 된다.**                              │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * DB의 특혜 글에서 「불」이 열 번 걸리는데 그중 다섯이 「이동불가」 속이었다.
 * 자리마다 **가장 긴 낱말부터** 맞춰 보는 것 하나로 갈린다.
 */
describe('긴 낱말이 먼저다', () => {
  it('이동불가를 통째로 잡는다', () => {
    expect(shape('이동불가 카드 1장 추가')).toEqual(['[immobilize]', '" 카드 1장 추가"'])
  })

  it('불은 불대로 잡는다', () => {
    expect(shape('불 카드')).toEqual(['[fire]', '" 카드"'])
  })

  it('한 줄에 둘 다 있어도 갈린다', () => {
    expect(shape('불 이동불가')).toEqual(['[fire]', '" "', '[immobilize]'])
  })
})

describe('붙어 있는 수', () => {
  it('수를 다는 표식은 붙은 수를 삼킨다', () => {
    expect(shape('밀기2 카드')).toEqual(['[push:2]', '" 카드"'])
    expect(shape('관통3')).toEqual(['[pierce:3]'])
  })

  /** `4장`의 `4`가 앞 낱말에 붙는 일이 없어야 한다. */
  it('수를 안 다는 표식은 삼키지 않는다', () => {
    expect(shape('불2')).toEqual(['[fire]', '"2"'])
  })

  it('띄어 적힌 수는 딸려 오지 않는다', () => {
    expect(shape('밀기 2')).toEqual(['[push]', '" 2"'])
  })
})

describe('그 밖', () => {
  /** 「대상」만 잡고 「추가」는 남긴다 — 그림이 삼킬 것은 표식이 가리키는 것까지다. */
  it('대상 추가에서 대상만 잡는다', () => {
    expect(shape('대상 추가')).toEqual(['[targets]', '" 추가"'])
  })

  it('가운뎃점으로 묶인 원소 둘을 각각 잡는다', () => {
    expect(shape('불·얼음')).toEqual(['[fire]', '"·"', '[ice]'])
  })

  it('빈 글은 아무것도 내지 않는다', () => {
    expect(splitPerkText('')).toEqual([])
  })
})

/**
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **값도 카드에 찍힌 그림이다 — 그림이 있는 일곱만 바꾼다.**                 │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * `+3`·`+4`는 특혜로만 나오는 값이라 팩에 메달이 없다. 그때는 글자 그대로 두는
 * 것이 맞다(구현 결정 115와 같은 결).
 */
describe('값 메달', () => {
  it('그림이 있는 일곱을 바꾼다', () => {
    expect(shape('+1 카드')).toEqual(['[값:p1]', '" 카드"'])
    expect(shape('+0')).toEqual(['[값:p0]'])
    expect(shape('+2')).toEqual(['[값:p2]'])
  })

  /** 빼기는 적는 사람 손에 따라 셋으로 갈린다 — 다른 값이 아니다. */
  it('빼기표 세 가지를 모두 받는다', () => {
    for (const sign of ['-', '\u2212', '\u2013']) {
      expect(shape(`${sign}1`)).toEqual(['[값:m1]'])
      expect(shape(`${sign}2`)).toEqual(['[값:m2]'])
    }
  })

  it('곱하기는 × 와 x 를 모두 받는다', () => {
    expect(shape('×0')).toEqual(['[값:x0]'])
    expect(shape('x2')).toEqual(['[값:x2]'])
  })

  /**
   * 팩에 메달이 없는 값도 **값으로 갈라낸다** — 덱 알약이 그러듯 숫자를 직접
   * 그려 메달 자리를 대신하기 때문이다. 글자로 흘려 두면 그 줄만 그림이 빠져
   * 어긋나 보인다. 형님이 "+3 특혜도 있나?"라고 물어 확인했다 — DB에 넷 있다.
   */
  it('메달이 없는 값도 값으로 갈라낸다', () => {
    expect(shape('+3 카드')).toEqual(['[값:p3]', '" 카드"'])
    expect(shape('+4')).toEqual(['[값:p4]'])
  })

  /** 카드 값이 아닌 것은 글자로 남는다. */
  it('없는 값은 글자로 남는다', () => {
    expect(shape('+5')).toEqual(['"+5"'])
    expect(shape('×1')).toEqual(['"×1"'])
    // 표준 덱의 빼기는 −1·−2뿐이다.
    expect(shape('−3')).toEqual(['"−3"'])
  })

  /** 그림 없는 값을 그릴 때 쓰므로 **적힌 그대로**를 들고 있어야 한다. */
  it('적힌 꼴을 그대로 들고 있는다', () => {
    const piece = splitPerkText('\u22122')[0]
    expect(piece).toEqual({ kind: 'value', valueId: 'm2', text: '\u22122' })
  })

  /** 자릿수가 둘이면 값이 아니다 — `+10`을 `+1`로 읽으면 안 된다. */
  it('뒤에 수가 더 붙으면 값이 아니다', () => {
    expect(shape('+10')).toEqual(['"+10"'])
  })

  it('한 줄에 값과 표식이 함께 있어도 갈린다', () => {
    expect(shape('+1 부상 카드 1장 추가')).toEqual([
      '[값:p1]',
      '" "',
      '[wound]',
      '" 카드 1장 추가"',
    ])
  })
})
