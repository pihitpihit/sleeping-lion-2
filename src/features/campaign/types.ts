/**
 * 축 ① 캠페인 기록지의 데이터 모델.
 *
 * SPEC 7장이 정본이다. 여기서는 **파티 기록지에 필요한 것까지만** 옮긴다 —
 * 캐릭터·시나리오 정산은 그 화면을 만들 때 더한다.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **기록지는 파티에 묶인다. 일지 항목 하나가 곧 파티 하나다.**              │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * 처음에는 '동행'(사람들의 파티)과 '일지'(기록지)를 따로 두었다. 그런데 화면에
 * 파티가 둘이 되어 어느 쪽을 만들라는 것인지 알 수 없었다 — 형님이 "두 개가
 * 따로 논다"고 짚었다. **실물에서는 하나다.** 파티 시트가 곧 그 파티이고 거기
 * 적힌 사람들이 파티원이다. 그래서 합쳤다.
 *
 * **저작권 경계.** 콘텐츠는 식별자·수치·**사용자가 직접 친 글자**로만 채운다
 * (SPEC 3장). 업적 이름을 우리가 담지 않고 사용자가 적는 것이 그래서다 —
 * 구현 결정 2가 이미 "사용자가 입력한 라벨"을 열어 두었다.
 */

/** 파티 기록지 한 벌. 서버의 `campaigns` 한 행과 같은 모양이다. */
export interface Campaign {
  id: string
  /** 어느 파티의 것인가. **서버가 옮기지 못하게 막는다**(트리거). */
  partyId: string
  /** 파티 이름과는 따로다 — 같은 파티가 다음 판을 새로 펼 수 있다. */
  name: string
  /** 지금 머무는 곳. 자유 입력이다 — 우리가 지명 목록을 갖고 있지 않다. */
  location: string
  /** 파티 메모. 여러 줄. */
  notes: string
  /**
   * 파티 업적.
   *
   * **사용자가 적는다.** 업적 이름은 시나리오·카드에 인쇄된 게임 콘텐츠이므로
   * 우리가 목록을 담지 않는다(SPEC 3장).
   */
  achievements: string[]
  /** −20 ~ +20. 상점 가격 보정이 여기서 나온다(`reputation.ts`). */
  reputation: number

  createdAt: number
  updatedAt: number
  /**
   * 고친 횟수.
   *
   * **서버가 찍는다.** 화면이 보내는 값을 믿지 않는다 — 오래된 화면이 낮은 값을
   * 보내면 낙관적 잠금이 그 순간 무의미해진다(SPEC 5.3).
   */
  version: number
}

/** 기록지에서 사람이 고치는 부분. 나머지는 서버가 관리한다. */
export type CampaignEdits = Partial<
  Pick<Campaign, 'name' | 'location' | 'notes' | 'achievements' | 'reputation'>
>
