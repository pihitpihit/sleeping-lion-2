/**
 * 축 ① 캠페인 기록지의 데이터 모델.
 *
 * SPEC 7장이 정본이다. 여기서는 **파티 기록지에 필요한 것까지만** 옮긴다 —
 * 캐릭터·시나리오 정산은 그 화면을 만들 때 더한다.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **기록지는 파티에 묶인다. 일지 항목 하나가 곧 파티 하나다.**              │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * 처음에는 '동행'(사람들의 파티)과 '일지'(기록지)를 따로 두었다. 그런데 화면에
 * 파티가 둘이 되어 어느 쪽을 만들라는 것인지 알 수 없었다 — 형님이 "두 개가
 * 따로 논다"고 짚었다. **실물에서는 하나다.** 파티 시트가 곧 그 파티이고 거기
 * 적힌 사람들이 파티원이다. 그래서 합쳤다.
 *
 * **저작권 경계.** 콘텐츠는 식별자·수치·**사용자가 직접 친 글자**로만 채운다
 * (SPEC 3장). 업적 이름을 우리가 담지 않고 사용자가 적는 것이 그래서다 —
 * 구현 결정 2가 이미 "사용자가 입력한 라벨"을 열어 두었다.
 */

/** 파티 기록지 한 벌. 서버의 `campaigns` 한 행과 같은 모양이다. */
export interface Campaign {
  id: string
  /** 어느 파티의 것인가. **서버가 옮기지 못하게 막는다**(트리거). */
  partyId: string
  /** 파티 이름과는 따로다 — 같은 파티가 다음 판을 새로 펼 수 있다. */
  name: string
  /** 지금 머무는 곳. 자유 입력이다 — 우리가 지명 목록을 갖고 있지 않다. */
  location: string
  /** 파티 메모. 여러 줄. */
  notes: string
  /**
   * 파티 업적.
   *
   * **사용자가 적는다.** 업적 이름은 시나리오·카드에 인쇄된 게임 콘텐츠이므로
   * 우리가 목록을 담지 않는다(SPEC 3장).
   */
  achievements: string[]
  /** −20 ~ +20. 상점 가격 보정이 여기서 나온다(`reputation.ts`). */
  reputation: number

  createdAt: number
  updatedAt: number
  /**
   * 고친 횟수.
   *
   * **서버가 찍는다.** 화면이 보내는 값을 믿지 않는다 — 오래된 화면이 낮은 값을
   * 보내면 낙관적 잠금이 그 순간 무의미해진다(SPEC 5.3).
   */
  version: number
}

/** 기록지에서 사람이 고치는 부분. 나머지는 서버가 관리한다. */
export type CampaignEdits = Partial<
  Pick<Campaign, 'name' | 'location' | 'notes' | 'achievements' | 'reputation'>
>

/* ==========================================================================
   캐릭터 — SPEC 7장
   --------------------------------------------------------------------------
   **파티원은 다 보고, 고치는 것은 제 것만**(SPEC 6장). 기록지가 파티원 누구나
   고치는 것과 다른 자리다 — 파티 상태는 함께 쓰는 것이고 캐릭터는 제 것이다.
   막는 것은 RLS다(`0005_characters.sql`).
   ========================================================================== */

/** 캐릭터 한 벌. 서버의 `characters` 한 행과 같은 모양이다. */
export interface Character {
  id: string
  /** 어느 기록지에 딸렸는가. **서버가 옮기지 못하게 막는다**(트리거). */
  /**
   * 어느 기록지(=파티)의 것인가. **아직 안 들었으면 `null`.**
   *
   * 캐릭터가 먼저 서고 파티에는 나중에 든다(2026-08-12, `0015`).
   */
  campaignId: string | null
  /** 누구의 것인가. 이 값이 곧 편집 권한이다. */
  ownerId: string
  /** 파티원 목록에 이 이름이 뜬다. 누가 주인인지 아는 데 쓴다. */
  ownerName: string

  name: string
  /**
   * 클래스 — **이름 대신 아이콘 번호**.
   *
   * Creator Pack `Class Icons and Augments.pdf`의 쪽 번호(1~21)다. 0은 아직 안
   * 고른 것이다. 클래스 이름은 게임 콘텐츠이고 잠긴 클래스는 이름 자체가
   * 스포일러라 담지 않는다(SPEC 3장). SPEC 12장 1을 이렇게 닫았다.
   */
  classIcon: number
  /**
   * 고른 클래스. 아직 클래스 수치를 안 넣었으면 `null`.
   *
   * **아이콘 번호와 함께 든다.** 아이콘만으로는 팩에 그림이 없는 클래스를 가리킬
   * 수 없고(`0012`), 반대로 클래스 표가 비어 있을 때는 아이콘만으로 골라야 한다.
   * 클래스를 고르면 그 클래스의 아이콘을 `classIcon`에도 적어 두므로 축 ②의
   * 이름표가 종전대로 그림을 찾는다.
   */
  classId: string | null

  level: number
  xp: number
  gold: number
  /** 전투 목표 체크마크. 셋이 모이면 퍽 하나다. */
  checkmarks: number

  /** 켜진 퍽 슬롯의 번호들. 어느 번호가 무엇인지는 우리가 알지 못한다. */
  perks: number[]
  /** 아이템 — **사용자가 친 글자**다(구현 결정 2). */
  items: string[]
  notes: string

  /** 은퇴한 캐릭터. 지우지 않고 접어 둔다. */
  retired: boolean

  createdAt: number
  updatedAt: number
  /** 고친 횟수. **서버가 찍는다.** */
  version: number
}

/** 캐릭터에서 사람이 고치는 부분. 나머지는 서버가 관리한다. */
/**
 * 시트에서 고칠 수 있는 칸.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ **이름과 클래스는 여기 없다. 생성할 때 정하고 그 뒤로는 못 바꾼다.**      │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * **클래스** — 캐릭터가 곧 클래스다. 레벨·경험·퍽·아이템이 전부 그 클래스에 매인
 * 값이라 클래스만 갈아 끼우면 남은 값들이 통째로 거짓이 된다. 특히 켜 둔 특혜
 * 상자 번호는 그 클래스의 특혜 표를 가리키므로(`0013`), 클래스가 바뀌면 같은
 * 번호가 딴 특혜를 가리키고 그것이 곧 공격 보정 덱의 구성이 된다.
 *
 * **이름** — 파티원은 이름으로 서로를 부른다. 축 ②의 이름표도 그것이고
 * (`satchel/roster.ts`) 전투에서 누구의 체력·덱인지 가리는 것도 그것이다.
 * **판 도중에 이름이 바뀌면 옆 사람이 보던 것이 딴 사람이 된다.**
 *
 * **여기서 빼는 것은 보낼 수조차 없게 하는 것이다.** 막는 것은 서버이며
 * (`0014`·`0017`) 타입에 남겨 두면 언젠가 다시 새어 든다.
 */
export type CharacterEdits = Partial<
  Pick<
    Character,
    'name' | 'level' | 'xp' | 'gold' | 'checkmarks' | 'perks' | 'items' | 'notes' | 'retired'
  >
>
