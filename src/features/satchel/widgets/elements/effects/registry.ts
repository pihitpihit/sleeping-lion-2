/**
 * 고급 효과 스위치.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ 지금은 꺼 둔다. 모든 원소가 공통 빛무리(음영)로 돌아간다.                 │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * **왜 껐나.** 사파리와 아이폰에서 크롬과 다르게 보인다는 이야기가 있었고 아직
 * 원인을 못 박았다. 헤드리스 WebKit에서는 재현되지 않았는데, 그것은 진짜
 * 사파리가 아니다 — 애플의 GPU 합성 경로가 빠져 있다. 여러 기기에서 안정된
 * 것을 확인한 뒤에 다시 켠다.
 *
 * **어떻게 다시 켜나.** 이 값을 `true`로 바꾸면 된다. 코드는 지우지 않았다.
 * 켜기 전에 `lab/fire.html`의 '사파리 진단' 스위치로 실기에서 확인할 것.
 *
 * 끈 상태에서도 FireEffect는 번들에 남는다(정적 import). 몇 KB짜리이고 다시
 * 켜는 것이 가까운 일이라 동적 import로 가르지 않았다.
 */
export const ADVANCED_EFFECTS = false

/**
 * 고급 효과가 준비된 원소.
 *
 * 컴포넌트와 한 파일에 두면 개발 중 빠른 새로고침이 깨지므로 갈라 둔다.
 */
const WITH_EFFECT = new Set(['fire'])

/**
 * 이 원소에 고유 효과를 쓸 것인가.
 *
 * 참이면 공통 빛무리를 끄고 고유 효과와 달아오른 석판으로 바꾼다 — 둘이
 * 겹치면 효과가 묻힌다.
 */
export function hasElementEffect(elementId: string): boolean {
  return ADVANCED_EFFECTS && WITH_EFFECT.has(elementId)
}
