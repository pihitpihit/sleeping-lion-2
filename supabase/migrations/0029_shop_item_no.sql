-- ============================================================================
-- 상점 아이템에 일련번호
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **실물 카드에 박힌 번호다 — 번영도 표가 그 번호로 말한다.**               │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 캠페인 시트의 번영도 표가 「1레벨: 001–014」처럼 **번호의 범위**로 적는다
-- (`rules/prosperity.ts`). 이름만으로는 그 표와 이을 수가 없다.
--
-- **이미 적어 둔 것은 −1을 준다**(형님이 정했다) — 「아직 안 적었다」는 뜻이며,
-- 0은 실제 번호일 수 있으므로 쓰지 않는다.
-- ============================================================================

alter table public.shop_items
  add column if not exists no smallint not null default -1;

/*
  같은 번호를 두 번 적지 않는다 — **다만 −1은 여럿이다**(아직 안 적은 것들).
  부분 인덱스로 그 자리만 비켜 둔다.
*/
create unique index if not exists shop_items_no_idx
  on public.shop_items (no)
  where no >= 0;
