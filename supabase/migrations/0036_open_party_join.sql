-- ============================================================================
-- 초대 링크를 걷고 누구나 들어간다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **승인은 문 앞에서 한 번이면 된다.**                                      │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 여태 파티에 드는 길은 초대 링크뿐이었다(구현 결정 21). 형님이 걷었다 — 승인된
-- 사람만 들어오는 앱이므로(`0004`) 그 안에서 또 한 번 문지기를 두면 우리끼리
-- 링크를 주고받는 품만 는다.
--
-- 이제 **승인된 사람이면 아무 파티에나 제 발로 든다.** 여전히 **제 이름으로만**
-- 든다 — 남을 끌어들이지는 못한다.
--
-- `invites`는 쓰는 데가 없어졌으므로 지운다. **묘비는 세우지 않는다**(구현 결정 229).
-- ============================================================================

drop policy if exists "구성원: 스스로 든다" on public.party_members;
create policy "구성원: 스스로 든다"
  on public.party_members for insert
  to authenticated
  with check (user_id = auth.uid() and public.is_approved());

drop table if exists public.invites;
