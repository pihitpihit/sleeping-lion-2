-- 시작 시나리오 표시
-- ----------------------------------------------------------------------------
-- 세계 지도에서 스티커를 누르면 「어디서 열렸나」를 들어오는 화살표로 그린다.
-- **처음부터 열려 있는 시나리오는 들어올 곳이 없다** — 그것을 따로 알려면 칸이
-- 있어야 한다. 들어오는 연결이 없는 것으로 가르면 보물·도시 이벤트로 열리는 곁가지
-- 시나리오까지 시작으로 읽힌다.
--
-- 값은 시나리오 목록과 같은 GHS(`initial`)에서 오고 **레포에 적지 않는다**(구현
-- 결정 532) — 이 파일에는 칸만 있다.
-- ============================================================================

alter table public.scenarios
  add column if not exists initial boolean not null default false;
