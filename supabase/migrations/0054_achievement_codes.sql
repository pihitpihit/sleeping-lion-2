-- ============================================================================
-- 업적에 GHS 열쇠를 붙인다
-- ----------------------------------------------------------------------------
-- 시나리오의 업적 조건(「이 업적이 있어야/없어야 열림」)과 보상(「깨면 얻음/잃음」)을
-- 셈하려면 GHS가 업적을 가리키는 열쇠(`the-merchant-flees` 꼴)와 우리 목록의 한글
-- 이름을 이어야 한다. 화면은 여전히 이름을 쓰고 셈할 때만 열쇠로 본다.
--
-- 사람이 적은 업적(`created_by`가 있는 것)은 열쇠가 없을 수 있다 — 그래서 비울 수
-- 있게 두고, 갈래 안에서 겹치지만 않게 한다.
--
-- **값은 레포에 적지 않는다**(구현 결정 532) — 업적 이름과 열쇠는 시나리오 목록과
-- 같은 GHS에서 와서 DB에만 들어간다. 이 파일에는 칸과 인덱스만 있다.
-- ============================================================================

alter table public.achievements
  add column if not exists code text;

create unique index if not exists achievements_code_idx
  on public.achievements (scope, code)
  where code is not null;
