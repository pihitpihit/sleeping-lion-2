-- ============================================================================
-- 기록에 '생성'을 더한다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **처음 한 줄이 없으면 기록이 중간부터 시작한다.**                         │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 지금까지는 시트에서 고친 것만 남았다. 그러면 기록을 펼쳤을 때 이 캐릭터가
-- 언제 생겼는지가 없어 **맨 아래 줄이 첫 정산**인 것처럼 읽힌다.
--
-- `reason`은 「어떤 경로로 이렇게 되었나」를 말하는 칸이다. 생성은 고친 것이
-- 아니므로 시나리오·직접·기타 어디에도 들어맞지 않아 갈래를 하나 더 둔다.
-- ============================================================================

alter table public.character_log
  drop constraint if exists character_log_reason_check;
alter table public.character_log
  add constraint character_log_reason_check
  check (reason in ('created', 'scenario', 'manual', 'other'));
