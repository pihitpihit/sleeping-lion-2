-- ============================================================================
-- 해산은 만든 사람만 한다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **파티원 아무나 지울 수 있게 두면 남이 세운 자리를 혼자 접는다.**         │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- `0037`은 「파티원이면 지운다, 다만 남의 캐릭터가 들어 있으면 안 된다」였다.
-- 형님이 좁혔다 — **만든 사람만** 한다. 남의 캐릭터 조건은 그대로 둔다: 만든
-- 사람이라도 남이 캐릭터를 넣어 두었으면 그 사람의 기록지를 혼자 날릴 수 없다.
--
-- 나가기와 갈리는 자리다. 나가는 것은 제 줄 하나이므로 누구나 언제든 하지만,
-- 해산은 **남는 모두의 것을 없앤다.**
-- ============================================================================

drop policy if exists "parties: 파티원이 해산한다" on public.parties;
create policy "parties: 만든 사람이 해산한다"
  on public.parties for delete to authenticated
  using (
    created_by = auth.uid()
    and not exists (
      select 1 from public.characters c
      join public.campaigns g on g.id = c.campaign_id
      where g.party_id = parties.id and c.owner_id <> auth.uid()
    )
  );
