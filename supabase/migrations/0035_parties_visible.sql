-- ============================================================================
-- 파티 목록은 승인된 사람이면 다 본다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **보이는 것과 드는 것은 다른 일이다.**                                    │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 여태 「속한 것만 본다」였다(`0001`). 그러면 아직 아무 파티에도 없는 사람은
-- **무엇이 있는지조차 볼 수 없어** 어디로 가야 할지 알 수 없다(형님이 정했다).
--
-- **여는 것은 이름과 만든 때까지다.** 기록지·캐릭터·전투는 그대로 파티원만 본다
-- (`campaigns`·`characters`·`battles`의 정책은 안 건드린다). 드는 것도 그대로
-- 초대 링크가 있어야 한다(구현 결정 21) — 목록에서 골라 들어갈 수는 없다.
--
-- 우리 DB는 공개가 아니다. 승인된 사람만 읽는다(`0004`) — 그 안에서의 이야기다.
-- ============================================================================

drop policy if exists "parties: 속한 것만 본다" on public.parties;
drop policy if exists "parties: 승인된 사람이 본다" on public.parties;
create policy "parties: 승인된 사람이 본다"
  on public.parties for select
  to authenticated
  using (public.is_approved());
