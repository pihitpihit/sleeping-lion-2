-- ============================================================================
-- 상점 이름은 공백을 안 가리고 견준다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **약간의 차이로 없다고 하면 같은 것이 두 벌 생긴다.**                     │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 「가죽 장화」와 「가죽장화」는 같은 물건이다. 앞뒤 공백만 털던 것으로는 그 둘이
-- 다른 줄로 앉는다 — 찾을 때 못 찾아 새로 적고, 그렇게 늘어난 목록이 다시
-- 헷갈리게 한다(형님이 짚었다).
--
-- 화면이 견주는 눈(`searchFold.ts`)과 **같은 셈**을 서버에도 둔다:
--   · NFC로 모으고 (맥에서 친 한글은 자모가 갈려 오는 일이 있다)
--   · 대소문자를 지우고
--   · **공백을 통째로 뺀다**
--
-- **저장되는 이름은 사람이 친 그대로다.** 이 셈은 겹치는지 볼 때만 쓴다.
-- ============================================================================

drop index if exists public.shop_items_name_idx;

create unique index if not exists shop_items_name_idx
  on public.shop_items ((lower(normalize(regexp_replace(name, '\s', '', 'g'), nfc))));
