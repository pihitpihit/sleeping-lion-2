-- ============================================================================
-- 아이템에 산 값을 함께 적는다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **들고 있는 것은 「산 그때의 값」으로 읽혀야 한다**(형님이 정했다).        │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 지금까지 `items`는 이름의 목록이었고, 시트는 값을 **상점 목록에서 되찾아** 적었다
-- (`costOf`). 그러면 둘이 어긋난다:
--
--   · 평판이 오르내리면 같은 물건을 **다른 값에 산다**(`shopPriceModifier`).
--   · 목록의 값을 누가 고치면 **이미 산 것의 값까지 따라 바뀐다.**
--
-- 산 값은 **그때 벌어진 사실**이라 되찾을 것이 아니라 적어 두어야 한다 — 은퇴한
-- 캐릭터를 그때의 값으로 베껴 두는 것과 같은 결이다(구현 결정 514).
--
-- **할인 전 값도 함께 적는다.** 얼마를 깎았는지는 낸 값만으로는 알 수 없고, 나중에
-- 평판이 바뀌면 다시 셈해 낼 수도 없다.
--
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **옛 줄은 이름만 있다 — 모르는 값은 비운다.**                             │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 이미 들고 있는 것들은 얼마에 샀는지 우리가 알 수 없다. 짐작해서 채우지 않는다
-- (구현 결정 115) — 화면은 값 없이 이름만 적는다.
-- ============================================================================

/*
  ┌──────────────────────────────────────────────────────────────────────────┐
  │ **`USING`에는 서브쿼리를 못 쓴다 — 두 걸음으로 나눈다.**                  │
  └──────────────────────────────────────────────────────────────────────────┘

  ① `text[]` → `jsonb`. `array_to_json`이 글자의 배열(`["가죽 장화"]`)을 낸다.
  ② 그 글자들을 `{"name": …}`으로 감싼다. 빈 배열이면 줄이 안 나와 `jsonb_agg`가
     `null`이 되므로 `coalesce`가 그 자리를 받는다.
*/
alter table public.characters
  alter column items drop default;

alter table public.characters
  alter column items type jsonb using array_to_json(items)::jsonb;

update public.characters
   set items = (
     select coalesce(jsonb_agg(jsonb_build_object('name', e)), '[]'::jsonb)
       from jsonb_array_elements_text(items) as e
   );

alter table public.characters
  alter column items set default '[]'::jsonb;
