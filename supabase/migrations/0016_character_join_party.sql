-- ============================================================================
-- 캐릭터가 파티에 들 수 있게 한다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **트리거가 `campaign_id`를 조용히 되돌리고 있었다.**                      │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- `touch_character`에 `new.campaign_id := old.campaign_id`가 있어, 파티를 옮기는
-- 갱신이 **오류 없이 통과하고 값만 안 바뀌었다.** 캐릭터가 파티 안에서만
-- 만들어지던 때에는 옮길 일이 없어 문제가 안 됐지만, `0015`로 파티 없이 세울 수
-- 있게 되면서 **파티에 드는 길 자체가 막혔다.**
--
-- **조용히 무시하는 것이 가장 나쁘다.** 화면은 저장했다고 하고 서버는 안 바꾼다 —
-- 사람이 알 길이 없다. 막을 것이면 거절해야 하고, 열 것이면 열어야 한다.
--
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **막는 자리를 트리거에서 RLS로 옮긴다.**                                  │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 고정을 둔 뜻은 "남의 파티로 캐릭터가 새어 나가지 않게"였다. 그 뜻은 `0015`의
-- `with check`가 **더 정확하게** 지킨다 — **제가 든 파티로만** 옮길 수 있고,
-- 아니면 거절된다. 그러니 트리거는 옮기기를 막을 것이 아니라 손을 떼면 된다.
--
-- `owner_id`·`created_at` 고정은 그대로 둔다. 그 둘은 바뀔 일이 없다.
-- ============================================================================

create or replace function public.touch_character()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  new.version := old.version + 1;
  -- **`campaign_id`는 여기서 고정하지 않는다.** 파티에 들고 나는 일이 있고,
  -- 어느 파티로 갈 수 있는지는 RLS가 본다(`0015`).
  new.owner_id := old.owner_id;
  new.created_at := old.created_at;
  return new;
end;
$$;
