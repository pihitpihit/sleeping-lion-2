-- ============================================================================
-- 전역 업적과 파티 업적을 가른다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **둘은 다른 표다. 그리고 전역은 여러 번 이룬다.**                         │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 실물 시트가 둘로 갈라 적는다(형님이 짚었다). 개봉 조건에 「전역 업적 … n회
-- 달성」이 있는 것으로 보아 **전역 업적은 되풀이해 이룰 수 있다** — 켰다/껐다가
-- 아니라 **몇 번 이뤘는가**다.
--
-- 그래서 담는 모양이 갈린다:
--   · 파티 업적 — 이름의 목록(`campaigns.achievements`, 그대로 둔다)
--   · 전역 업적 — `{ 이름: 횟수 }`
--
-- 목록 표(`achievements`)에는 어느 쪽 것인지만 더한다. 옛 줄은 파티 업적이다 —
-- 지금까지 적어 둔 것이 그것뿐이다.
-- ============================================================================

alter table public.achievements
  add column if not exists scope text not null default 'party'
  check (scope in ('party', 'global'));

/*
  이름이 겹치지 않게 보는 눈은 그대로 두되 **갈래 안에서만** 본다 — 같은 이름의
  파티 업적과 전역 업적이 따로 있을 수 있다.
*/
drop index if exists public.achievements_name_idx;
create unique index if not exists achievements_name_idx
  on public.achievements (scope, (lower(normalize(regexp_replace(name, '\s', '', 'g'), nfc))));

-- ----------------------------------------------------------------------------
-- 파티가 이룬 전역 업적 — `{ 이름: 횟수 }`
-- ----------------------------------------------------------------------------
-- 개봉 조건 진행과 같은 모양이다(`0027`). 없는 열쇠는 0으로 읽으므로 빈 값을 굳이
-- 적어 두지 않는다.

alter table public.campaigns
  add column if not exists global_achievements jsonb not null default '{}'::jsonb;
