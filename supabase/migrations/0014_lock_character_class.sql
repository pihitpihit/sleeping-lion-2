-- ============================================================================
-- 캐릭터의 클래스는 세울 때 정하고 그 뒤로는 못 바꾼다
-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **캐릭터가 곧 클래스다.**                                                 │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 바위심장이 도끼투척수로 바뀌는 일은 없다. 그러고 싶으면 거두고 새로 세운다.
-- 레벨·경험·퍽·아이템이 전부 그 클래스에 매인 값이라 **클래스만 갈아 끼우면
-- 남은 값들이 통째로 거짓이 된다** — 특히 켜 둔 특혜 상자 번호는 그 클래스의
-- 특혜 표를 가리키므로(`0013`), 클래스가 바뀌면 같은 번호가 딴 특혜를 가리키고
-- 그것이 곧 공격 보정 덱의 구성이 된다.
--
-- 시트에서 고르는 칸을 걷었지만 **화면이 안 내는 것만으로는 잠긴 것이 아니다**
-- (구현 결정 44). 레포와 번들이 공개이므로 아무나 REST로 직접 찌를 수 있다.
--
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **정해진 적 없는 클래스는 한 번 정할 수 있다.**                           │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 클래스를 안 고른 채로도 캐릭터를 세울 수 있으므로(`Roster`), 무조건 잠그면
-- 그런 캐릭터가 **영영 클래스 없이 갇힌다.** 아직 안 정한 것과 정한 것을 가른다.
--
-- `campaigns`가 파티를 못 옮기게 막아 둔 것과 같은 짜임이다.
-- ============================================================================

create or replace function public.lock_character_class()
returns trigger
language plpgsql
as $$
begin
  -- 한 번이라도 정해졌는가. `class_id`가 정본이고, 클래스 표가 없던 시절에
  -- 만들어진 캐릭터는 아이콘 번호만 들고 있다(`0012`) — 둘 다 본다.
  if (old.class_id is not null or old.class_icon <> 0) then
    if new.class_id is distinct from old.class_id or new.class_icon <> old.class_icon then
      raise exception '캐릭터의 클래스는 바꿀 수 없습니다. 거두고 새로 세우십시오.'
        using errcode = 'check_violation';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists characters_lock_class on public.characters;
create trigger characters_lock_class
  before update on public.characters
  for each row execute function public.lock_character_class();
