-- ----------------------------------------------------------------------------
-- ┌──────────────────────────────────────────────────────────────────────────┐
-- │ **레벨은 고르는 값이 아니라 눈금에서 나온다.**                            │
-- └──────────────────────────────────────────────────────────────────────────┘
--
-- 형님이 실물 판을 찍어 보내 주었다 — 네모가 길게 늘어서고 어떤 자리 위에 레벨이
-- 굵게 적혀 있다. 캐릭터 레벨을 경험치에서 뽑는 것과 같은 결이다(구현 결정 223):
-- **담는 것은 칸 수 하나**이고 레벨은 화면이 셈한다(`rules/prosperity.ts`).
--
-- 앞서 `0031`이 이 칸을 「레벨 1~9」로 두었는데, 그때 들어간 값은 1(기본값)뿐이라
-- 칸 수로 읽어도 어긋나지 않는다 — 1칸이면 여전히 1레벨이다.
-- ============================================================================

alter table public.campaigns
  drop constraint if exists campaigns_prosperity_check;

alter table public.campaigns
  add constraint campaigns_prosperity_check check (prosperity between 0 and 64);
